/**
 * 内置示例角色卡。
 *
 * 为什么放进前端代码而不是服务端种子：clone 下来 `pnpm dev` 就能用，
 * 不依赖数据库预置、也不需要用户先去社区找素材。
 * 内容与头像全部原创，可自由分发。
 *
 * 结构用 V2（`spec: chara_card_v2` + `data`），导入时走和社区卡完全相同的解析路径。
 * `avatarKey` 指向 samples/avatars.ts 里内联的 PNG；导入后由前端补一次头像上传。
 */

export interface SampleCard {
  /** 展示用名字（同时作为去重键） */
  name: string;
  /** 一句话介绍 */
  blurb: string;
  /** 头像的键（见 avatars.ts） */
  avatarKey: string;
  card: Record<string, unknown>;
  /** 内置小剧本：到第几轮发生什么事（播种时一并写入） */
  events?: { atTurn: number; title: string; content: string }[];
}

/** 少写点重复结构：把常用字段拼成 V2 卡。 */
function v2(data: Record<string, unknown>): Record<string, unknown> {
  return { spec: 'chara_card_v2', spec_version: '2.0', data };
}

